"""
JA4X: how a certificate was generated (FoxIO JA4+). Three 12-character hex parts `a_b_c`: a hash of the issuer's
RDN attribute types (OIDs, in order), of the subject's, and of the extension OIDs, so it ignores the names and keys
themselves. Certificates generated by the same tool or template share it; CA-issued web certificates share a few
very common values, so a shared JA4X only links domains when the value is rare.
"""
import re

import pandas as pd

from core.cert_utils import publicly_trusted
from core.intel_data import DEVICE_JA4X, DUAL_USE_JA4X, JA4X_DETAILS, JA4X_SOURCE, KNOWN_JA4X

JA4X_RE = re.compile(r"^[0-9a-f]{12}_[0-9a-f]{12}_[0-9a-f]{12}$")
EMPTY_PART = "000000000000"
EMPTY_HASH = "e3b0c44298fc"   # SHA-256 of nothing, truncated: no extensions
RARE_MAX, UNCOMMON_MAX = 50, 1000   # certificates with the value in the Certificates API: rare / uncommon / common
SUMMARY_COLUMNS = ["JA4X", "Known As", "Domains", "Domain Count", "Certificates", "Issuers", "Self-signed", "Layout",
                   "Off Public CA"]
NOTABLE_COLUMNS = ["JA4X", "Why", "Domains", "Certificates", "In Window"]


def normalize(value):
    """The JA4X as a lowercase string, or "" when the value is missing or not a JA4X."""
    text = str(value or "").strip().lower() if not (isinstance(value, float) and pd.isna(value)) else ""
    return text if JA4X_RE.match(text) else ""


def cert_ja4x(cert):
    return normalize(cert.get("JA4X") if hasattr(cert, "get") else None)


KIND_LABELS = {"c2": "C2 / malware", "dual-use": "dual-use tool", "device": "network device"}


def known_ja4x(value):
    """(name, "c2", "dual-use" or "device") for a fingerprint on the built-in lists, or None."""
    value = normalize(value)
    if value in KNOWN_JA4X:
        return KNOWN_JA4X[value], "c2"
    if value in DUAL_USE_JA4X:
        return DUAL_USE_JA4X[value], "dual-use"
    if value in DEVICE_JA4X:
        return DEVICE_JA4X[value], "device"
    return None


def generated_layout(value):
    """
    Whether a JA4X has an empty issuer (no issuer attributes at all): no CA issues such a certificate; code that
    generates its own does (Sliver and Havoc C2 build random certificates this way).
    """
    value = normalize(value)
    return bool(value) and value.split("_")[0] == EMPTY_PART


def note(value):
    """A short pointer for tables: the known tool and its kind, else what the layout says ("" for a usual layout)."""
    match = known_ja4x(value)
    if match:
        return f"{match[0]} ({KIND_LABELS[match[1]]})"
    return layout_note(value) if generated_layout(value) or "issuer = subject" in layout_note(value) else ""


def layout_note(value):
    """What the three parts say about the certificate's layout, e.g. "issuer = subject layout, no extensions"."""
    value = normalize(value)
    if not value:
        return ""
    issuer, subject, extensions = value.split("_")
    notes = []
    if issuer == EMPTY_PART:
        notes.append("empty issuer")
    if subject == EMPTY_PART:
        notes.append("empty subject")
    if issuer == subject and issuer != EMPTY_PART:
        notes.append("issuer = subject layout")
    if extensions in (EMPTY_PART, EMPTY_HASH):
        notes.append("no extensions")
    return ", ".join(notes)


def rarity(total, relation="eq"):
    """How common a JA4X is, from the number of certificates with it in the Certificates API."""
    if total is None:
        return ""
    if relation == "gte" or total > UNCOMMON_MAX:
        return "Common (CA or platform default)"
    if total > RARE_MAX:
        return "Uncommon"
    return "Rare"


def search_query(value):
    """The CertsQL query for every certificate with this JA4X (without the version line)."""
    return f'ja4x equals "{normalize(value)}"'


def summary(ssl):
    """One row per JA4X in the run's certificates: the domains and certificates with it, known tool, layout."""
    if ssl is None or ssl.empty or "JA4X" not in ssl.columns:
        return pd.DataFrame(columns=SUMMARY_COLUMNS)
    certs = ssl.assign(JA4X=ssl["JA4X"].map(normalize))
    certs = certs[certs["JA4X"] != ""]
    if certs.empty:
        return pd.DataFrame(columns=SUMMARY_COLUMNS)
    self_signed = certs["Is Self Signed"] if "Is Self Signed" in certs.columns else pd.Series(False, index=certs.index)
    certs = certs.assign(_self=self_signed.fillna(False).astype(bool))
    rows = []
    for value, group in certs.groupby("JA4X"):
        known = known_ja4x(value)
        rows.append({
            "JA4X": value,
            "Known As": known[0] if known else "",
            "Domains": ", ".join(sorted(set(map(str, group["Domain"])))),
            "Domain Count": group["Domain"].nunique(),
            "Certificates": group["Hash"].nunique() if "Hash" in group.columns else len(group),
            "Issuers": ", ".join(sorted({str(i) for i in group.get("Issuer", pd.Series(dtype=str)) if str(i).strip()})),
            "Self-signed": bool(group["_self"].any()),
            "Layout": layout_note(value),
            "Off Public CA": any(publicly_trusted(cert) is not True for _, cert in group.iterrows()),
        })
    frame = pd.DataFrame(rows, columns=SUMMARY_COLUMNS)
    frame["_known"] = frame["Known As"] != ""
    return frame.sort_values(["_known", "Domain Count", "Certificates"], ascending=False, kind="stable") \
        .drop(columns="_known").reset_index(drop=True)


def notable(frame, in_window=None):
    """
    The JA4X values worth an analyst's look, from summary(): a known tool or device, a code-generated layout (empty
    issuer), or a value two or more domains share off public CAs (a shared CA layout means nothing). NOTABLE_COLUMNS,
    with why each matters; most telling first. `in_window`: the values in the analysis window (None: all are).
    """
    if frame is None or frame.empty:
        return pd.DataFrame(columns=NOTABLE_COLUMNS)
    rows = []
    for row in frame.to_dict("records"):
        match = known_ja4x(row["JA4X"])
        if match:
            why, rank = f"{match[0]}: {KIND_LABELS[match[1]]} fingerprint", {"c2": 0, "device": 1}.get(match[1], 2)
        elif generated_layout(row["JA4X"]):
            why, rank = "Empty issuer: generated by code, not a CA (Sliver / Havoc style)", 1
        elif row.get("Off Public CA") and row["Domain Count"] > 1:
            why, rank = f"Shared by {row['Domain Count']} of your domains, not from a public CA: one tool or template", 3
        else:
            continue
        rows.append({"JA4X": row["JA4X"], "Why": why, "Domains": row["Domains"], "Certificates": row["Certificates"],
                     "In Window": in_window is None or row["JA4X"] in in_window, "_rank": rank})
    if not rows:
        return pd.DataFrame(columns=NOTABLE_COLUMNS)
    return pd.DataFrame(rows).sort_values("_rank", kind="stable").drop(columns="_rank").reset_index(drop=True)


def _part(name, value, subject=None):
    """(what part `name` of a JA4X says, short label) for the fingerprint card."""
    if value == EMPTY_PART:
        return f"No {name} attributes", "empty"
    if name == "issuer" and value == subject:
        return "Same attribute types as the subject: a self-signed or tool-made layout", "same as subject"
    if name == "extensions" and value == EMPTY_HASH:
        return "No extensions", "none"
    what = {"issuer": "The issuer's attribute types (C, O, CN …) in order",
            "subject": "The subject's attribute types in order",
            "extensions": "The extension OIDs in order"}[name]
    return what, "hash"


def describe(value):
    """
    A JA4X fingerprint card: the three parts and what they say, the built-in match (name, kind, source) and its
    details (JA4X_DETAILS). None when `value` is not a JA4X.
    """
    value = normalize(value)
    if not value:
        return None
    issuer, subject, extensions = value.split("_")
    parts = [("Issuer layout", issuer, *_part("issuer", issuer, subject)),
             ("Subject layout", subject, *_part("subject", subject)),
             ("Extensions", extensions, *_part("extensions", extensions))]
    match = known_ja4x(value)
    if match:
        verdict = f"{match[0]}: {KIND_LABELS[match[1]]} fingerprint"
    elif generated_layout(value):
        verdict = "Code-generated layout (empty issuer): no certificate authority issues this; Sliver / Havoc style"
    else:
        verdict = "Not on a built-in list"
    return {"value": value, "parts": parts, "known": match, "kind": match[1] if match else "",
            "verdict": verdict, "source": JA4X_SOURCE if match else "", "details": JA4X_DETAILS.get(value, {}),
            "layout": layout_note(value)}


def _texts(cell):
    """The lowercase strings of a certificate field (a string, or a list of them)."""
    items = cell if isinstance(cell, (list, tuple, set)) else [cell]
    return {str(item).strip().lower() for item in items if item is not None}


def default_matches(value, certs):
    """
    (certificates with JA4X `value`, of them with the tool's default names) in `certs`: a match with the default
    names is the tool's own certificate, one without shares only the layout. (n, None) when no default is known.
    """
    value = normalize(value)
    if certs is None or certs.empty or "JA4X" not in certs.columns:
        return 0, None
    mine = certs[certs["JA4X"].map(normalize) == value]
    mine = mine.drop_duplicates("Hash") if "Hash" in mine.columns else mine
    default = JA4X_DETAILS.get(value, {}).get("default")
    if not default:
        return len(mine), None
    hit = pd.Series(False, index=mine.index)
    for column, expected in default.items():
        if column in mine.columns:
            hit |= pd.Series([expected.lower() in _texts(cell) for cell in mine[column]], index=mine.index)
    return len(mine), int(hit.sum())
