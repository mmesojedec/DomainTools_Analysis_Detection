"""
JA4X: how a certificate was generated (FoxIO JA4+). Three 12-character hex parts `a_b_c`: a hash of the issuer's
RDN attribute types (OIDs, in order), of the subject's, and of the extension OIDs, so it ignores the names and keys
themselves. Certificates generated by the same tool or template share it; CA-issued web certificates share a few
very common values, so a shared JA4X only links domains when the value is rare.
"""
import re

import pandas as pd

from core.intel_data import DUAL_USE_JA4X, KNOWN_JA4X

JA4X_RE = re.compile(r"^[0-9a-f]{12}_[0-9a-f]{12}_[0-9a-f]{12}$")
EMPTY_PART = "000000000000"
EMPTY_HASH = "e3b0c44298fc"   # SHA-256 of nothing, truncated: no extensions
RARE_MAX, UNCOMMON_MAX = 50, 1000   # certificates with the value in the Certificates API: rare / uncommon / common
SUMMARY_COLUMNS = ["JA4X", "Known As", "Domains", "Domain Count", "Certificates", "Issuers", "Self-signed", "Layout"]


def normalize(value):
    """The JA4X as a lowercase string, or "" when the value is missing or not a JA4X."""
    text = str(value or "").strip().lower() if not (isinstance(value, float) and pd.isna(value)) else ""
    return text if JA4X_RE.match(text) else ""


def cert_ja4x(cert):
    return normalize(cert.get("JA4X") if hasattr(cert, "get") else None)


def known_ja4x(value):
    """(name, "c2" or "dual-use") for a fingerprint on the built-in lists, or None."""
    value = normalize(value)
    if value in KNOWN_JA4X:
        return KNOWN_JA4X[value], "c2"
    if value in DUAL_USE_JA4X:
        return DUAL_USE_JA4X[value], "dual-use"
    return None


def layout_note(value):
    """What the three parts say about the certificate's layout, e.g. "issuer = subject layout, no extensions"."""
    value = normalize(value)
    if not value:
        return ""
    issuer, subject, extensions = value.split("_")
    notes = []
    if issuer == EMPTY_PART:
        notes.append("empty issuer")
    if subject == EMPTY_PART:
        notes.append("empty subject")
    if issuer == subject and issuer != EMPTY_PART:
        notes.append("issuer = subject layout")
    if extensions in (EMPTY_PART, EMPTY_HASH):
        notes.append("no extensions")
    return ", ".join(notes)


def rarity(total, relation="eq"):
    """How common a JA4X is, from the number of certificates with it in the Certificates API."""
    if total is None:
        return ""
    if relation == "gte" or total > UNCOMMON_MAX:
        return "Common (CA or platform default)"
    if total > RARE_MAX:
        return "Uncommon"
    return "Rare"


def search_query(value):
    """The CertsQL query for every certificate with this JA4X (without the version line)."""
    return f'ja4x equals "{normalize(value)}"'


def summary(ssl):
    """One row per JA4X in the run's certificates: the domains and certificates with it, known tool, layout."""
    if ssl is None or ssl.empty or "JA4X" not in ssl.columns:
        return pd.DataFrame(columns=SUMMARY_COLUMNS)
    certs = ssl.assign(JA4X=ssl["JA4X"].map(normalize))
    certs = certs[certs["JA4X"] != ""]
    if certs.empty:
        return pd.DataFrame(columns=SUMMARY_COLUMNS)
    self_signed = certs["Is Self Signed"] if "Is Self Signed" in certs.columns else pd.Series(False, index=certs.index)
    certs = certs.assign(_self=self_signed.fillna(False).astype(bool))
    rows = []
    for value, group in certs.groupby("JA4X"):
        known = known_ja4x(value)
        rows.append({
            "JA4X": value,
            "Known As": known[0] if known else "",
            "Domains": ", ".join(sorted(set(map(str, group["Domain"])))),
            "Domain Count": group["Domain"].nunique(),
            "Certificates": group["Hash"].nunique() if "Hash" in group.columns else len(group),
            "Issuers": ", ".join(sorted({str(i) for i in group.get("Issuer", pd.Series(dtype=str)) if str(i).strip()})),
            "Self-signed": bool(group["_self"].any()),
            "Layout": layout_note(value),
        })
    frame = pd.DataFrame(rows, columns=SUMMARY_COLUMNS)
    frame["_known"] = frame["Known As"] != ""
    return frame.sort_values(["_known", "Domain Count", "Certificates"], ascending=False, kind="stable") \
        .drop(columns="_known").reset_index(drop=True)
